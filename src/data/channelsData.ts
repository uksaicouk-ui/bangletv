import { Channel } from '../types';
import { IPTV_CHANNELS } from './iptvRegistry';

export const CHANNELS: Channel[] = IPTV_CHANNELS.map((ch) => ({
  id: ch.id,
  number: ch.number,
  name: ch.name,
  banglaName: ch.banglaName,
  category: ch.category as any,
  country: ch.country,
  region: ch.region as any,
  language: ch.language as any,
  communityNodeId: ch.id.includes('london') ? 'node-london-uk' : ch.id.includes('ny') ? 'node-ny-usa' : ch.id.includes('sylhet') ? 'node-sylhet-bd' : ch.region === 'Bangladesh' ? 'node-dhaka-central' : 'node-global-ref',
  communityNodeName: ch.originNode,
  logo: ch.logo,
  streamUrl: ch.sources[0]?.url || '',
  embedType: ch.sources[0]?.type || 'youtube',
  sources: ch.sources,
  activeSourceIndex: ch.activeSourceIndex,
  isLive: ch.isLive,
  status: ch.status,
  currentShow: ch.currentShow,
  nextShow: ch.nextShow,
  epgCurrent: ch.epgCurrent,
  epgNext: ch.epgNext,
  viewersCount: ch.viewersCount,
  resolution: ch.resolution,
  broadcastLanguage: ch.language,
  description: ch.description,
  editorialNote: ch.editorialNote,
  tags: ch.tags,
}));
